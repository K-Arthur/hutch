#!/usr/bin/env python3
"""Compile website/tokens.json into website/tokens.css and validate it.

Single source of truth for hutch brand tokens (primitive -> semantic -> component).
Validation: duplicate names, unresolved references, reference cycles, contrast
pairs from color.verify, and output drift (--check compares against the file on
disk; used by CI via tests/test_site_tokens.py).

Stdlib only. Usage:
    python scripts/build_site_tokens.py          # write tokens.css
    python scripts/build_site_tokens.py --check  # fail on drift or errors
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "website" / "tokens.json"
OUTPUT = ROOT / "website" / "tokens.css"

REF = re.compile(r"^\{([^{}]+)\}$")


class TokenError(Exception):
    pass


def flatten(node: dict, path: tuple[str, ...], out: dict[str, dict]) -> None:
    for key, val in node.items():
        if key.startswith("$"):
            continue
        child = path + (key,)
        if isinstance(val, dict):
            if "$value" in val:
                name = ".".join(child)
                if name in out:
                    raise TokenError(f"duplicate token: {name}")
                out[name] = val
            else:
                flatten(val, child, out)


def resolve(tokens: dict[str, dict], name: str, stack: tuple[str, ...]) -> str:
    if name in stack:
        raise TokenError("reference cycle: " + " -> ".join(stack + (name,)))
    tok = tokens.get(name)
    if tok is None:
        raise TokenError(f"unresolved reference: {{{name}}}")
    val = tok["$value"]
    if isinstance(val, str):
        m = REF.match(val.strip())
        if m:
            return resolve(tokens, m.group(1), stack + (name,))
    return val


def as_str(tokens: dict[str, dict], name: str) -> str:
    val = resolve(tokens, name, ())
    if isinstance(val, (int, float)) and not isinstance(val, bool):
        return str(val)
    if not isinstance(val, str):
        raise TokenError(f"token {name} must compile to a string, got {val!r}")
    return val


# ---------------------------------------------------------------- contrast
HEX = re.compile(r"^#([0-9a-f]{3}|[0-9a-f]{6})$", re.I)


def srgb(value: str) -> tuple[float, float, float]:
    v = value.strip()
    m = HEX.match(v)
    if m:
        h = m.group(1)
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        return tuple(int(h[i : i + 2], 16) / 255 for i in (0, 2, 4))  # type: ignore
    m = re.match(r"^rgb\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*\)$", v)
    if m:
        return tuple(float(m.group(i)) / 255 for i in (1, 2, 3))  # type: ignore
    raise TokenError(f"cannot parse color (opaque sRGB only): {value!r}")


def lum(c: tuple[float, float, float]) -> float:
    ch = [(v / 12.92) if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in c]
    return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]


def ratio(a: str, b: str) -> float:
    la, lb = lum(srgb(a)), lum(srgb(b))
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def check_contrast(tokens: dict[str, dict]) -> list[str]:
    problems: list[str] = []
    pairs = tokens.get("color.verify", {}).get("$extensions", {}).get("site.textPairs", [])
    for row in pairs:
        fg_name, bg_name = row[0], row[1]
        minimum = row[2] if len(row) > 2 else 4.5
        fg, bg = as_str(tokens, fg_name), as_str(tokens, bg_name)
        if "rgba" in fg or "rgba" in bg:
            problems.append(f"verify pair must be opaque: {fg_name} on {bg_name}")
            continue
        got = ratio(fg, bg)
        if got < minimum:
            problems.append(
                f"contrast {fg_name} on {bg_name}: {got:.2f}:1 < {minimum}:1 ({fg} / {bg})"
            )
    return problems


# ------------------------------------------------------------------- emit
def css_name(path: str) -> str:
    return "--" + path.replace(".", "-")


def emit(tokens: dict[str, dict]) -> str:
    lines = [
        "/* Generated by scripts/build_site_tokens.py from website/tokens.json.",
        " * DO NOT EDIT — edit the token source and regenerate.",
        " */",
        ":root {",
    ]
    order = ["color", "font", "text", "space", "size", "radius", "motion", "layer"]
    for group in order:
        lines.append(f"  /* {group} */")
        for name in sorted(n for n in tokens if n.split(".")[0] == group):
            val = as_str(tokens, name)
            if isinstance(val, (int, float)):
                val = str(val)
            lines.append(f"  {css_name(name)}: {val};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def load() -> dict[str, dict]:
    raw = json.loads(TOKENS.read_text())
    tokens: dict[str, dict] = {}
    flatten(raw, (), tokens)
    # force resolution so bad refs/cycles raise even if never emitted
    for name in tokens:
        if name.split(".")[0] in ("color", "font", "text", "space", "size", "radius", "motion", "layer"):
            as_str(tokens, name)
    return tokens


def main(argv: list[str]) -> int:
    check = "--check" in argv
    try:
        tokens = load()
        problems = check_contrast(tokens)
        if problems:
            print("\n".join("contrast: " + p for p in problems), file=sys.stderr)
            return 1
        css = emit(tokens)
    except (TokenError, json.JSONDecodeError) as exc:
        print(f"token error: {exc}", file=sys.stderr)
        return 1
    if check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != css:
            print("drift: website/tokens.css is stale — run scripts/build_site_tokens.py", file=sys.stderr)
            return 1
        print(f"ok: {len(tokens)} tokens, no drift, contrast verified")
        return 0
    OUTPUT.write_text(css)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(tokens)} tokens)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
