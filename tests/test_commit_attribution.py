def run_checker(*args: str, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(CHECKER), *args],
        cwd=str(cwd or ROOT),
        text=True,
        capture_output=True,
        check=False,
    )


def check_message(tmp_path: Path, message: str) -> subprocess.CompletedProcess[str]:
    path = tmp_path / "COMMIT_EDITMSG"
    path.write_text(message, encoding="utf-8")
    return run_checker("--message-file", str(path))


def git(repo: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", *GIT_CONFIG, *args],
        cwd=str(repo),
        text=True,
        capture_output=True,
        check=True,
    )


def init_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    git(repo, "init", "-q", "-b", "main")
    return repo


def commit_message_file(repo: Path, tmp_path: Path, message: str) -> str:
    message_path = tmp_path / "message.txt"
    message_path.write_text(message, encoding="utf-8")
    git(repo, "commit", "-q", "--allow-empty", "--cleanup=verbatim", "-F", str(message_path))
    return git(repo, "rev-parse", "HEAD").stdout.strip()


