def test_hook_is_executable() -> None:
    assert os.access(HOOK, os.X_OK)


def test_hook_rejects_ai_attribution(tmp_path: Path) -> None:
    path = tmp_path / "COMMIT_EDITMSG"
    path.write_text(f"Add the menu\n\n{AI_COAUTHOR_TRAILER}\n", encoding="utf-8")
    result = subprocess.run(
        ["sh", str(HOOK), str(path)],
        cwd=str(ROOT),
        text=True,
        capture_output=True,
        check=False,
    )
    assert result.returncode == 1
    assert "AI attribution" in result.stderr


