def test_range_flags_only_offending_commits(tmp_path: Path) -> None:
    repo = init_repo(tmp_path)
    preserved = commit_message_file(
        repo,
        tmp_path,
        f"Preserved history\n\n{AI_COAUTHOR_TRAILER}\n",
    )
    base = commit_message_file(repo, tmp_path, "Clean base commit\n")
    offending = commit_message_file(
        repo,
        tmp_path,
        f"Add the menu\n\n{AI_COAUTHOR_TRAILER}\n",
    )
    clean = commit_message_file(repo, tmp_path, "Document the menu\n")

    result = run_checker("--range", f"{base}..HEAD", cwd=repo)
    assert result.returncode == 1, result.stdout
    # Offending commits are reported as "  <sha>  <subject>"; the base of the
    # range only appears in the range spec echo, never as a finding.
    assert f"  {offending}  Add the menu" in result.stderr
    assert f"  {clean}  " not in result.stderr
    assert f"  {base}  " not in result.stderr
    assert f"  {preserved}  " not in result.stderr


def test_range_excluding_preserved_history_still_flags_new_commit(tmp_path: Path) -> None:
    repo = init_repo(tmp_path)
    preserved = commit_message_file(
        repo,
        tmp_path,
        f"Preserved history\n\n{AI_COAUTHOR_TRAILER}\n",
    )
    offending = commit_message_file(
        repo,
        tmp_path,
        f"Add the menu\n\n{AI_COAUTHOR_TRAILER}\n",
    )

    result = run_checker("--range", f"{preserved}..HEAD", cwd=repo)
    assert result.returncode == 1, result.stdout
    assert f"  {offending}  " in result.stderr
    assert f"  {preserved}  " not in result.stderr


