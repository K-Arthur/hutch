"""XLSX generator gates: cached formula values (E6), explicit cell types (E12), bounds.

Every test reads generated bytes back through openpyxl, the independent reader the
promotion gate itself uses, never through the writer's own objects.
"""

from __future__ import annotations

import io
import json
import zipfile
from datetime import date, datetime

import pytest
from openpyxl import load_workbook

from hutch.documents.docgen import DocumentGenerationError, generate, supported_formats
from hutch.documents.docgen import xlsx as xlsx_module


def _gen(spec: dict):
    return generate("xlsx", spec)


def _cached_grid(data: bytes, name: str) -> list[list]:
    book = load_workbook(io.BytesIO(data), data_only=True, read_only=True)
    try:
        return [list(row) for row in book[name].iter_rows(values_only=True)]
    finally:
        book.close()


def test_registration_and_generator_string():
    assert "xlsx" in supported_formats()
    doc = _gen({"sheets": [{"name": "S", "rows": [[1]]}]})
    assert doc.generator == xlsx_module.GENERATOR
    assert doc.generator.startswith("hutch docgen xlsx 1.0 (XlsxWriter ")
    assert "openpyxl" in doc.generator
    assert doc.data[:2] == b"PK", "an xlsx is a zip of parts"


def test_happy_path_roundtrip_via_independent_reader():
    doc = _gen({"sheets": [
        {"name": "Ledger", "header": ["ID", "Amount", "When"],
         "freeze_header": True, "col_widths": [14, 10, 12],
         "rows": [
             ["00123", 42, {"date": "2026-01-31"}],
             ["00124", 2.5, {"date": "2026-02-01"}],
             ["TOTAL", {"formula": "=SUM(B2:B3)", "value": 44.5},
              {"formula": "=COUNT(B2:B3)", "value": 2}]]},
        {"name": "Ranges", "rows": [
            [3, 1, 4, 1, 5],
            [{"formula": "=MIN(A1:E1)", "value": 1},
             {"formula": "=MAX(A1:E1)", "value": 5},
             {"formula": "=AVERAGE(A1:E1)", "value": 2.8},
             {"formula": "=SUM(A1:E1)", "value": 14},
             {"formula": "=COUNT(A1:E1)", "value": 5}]]}]})
    assert doc.validation_state == "passed" and doc.findings == []
    assert doc.preview_mode == "structure"

    book = load_workbook(io.BytesIO(doc.data))
    try:
        assert book.sheetnames == ["Ledger", "Ranges"]
        ledger = book["Ledger"]
        assert ledger.freeze_panes == "A2" and book["Ranges"].freeze_panes is None
        assert ledger["A2"].value == "00123" and ledger["A2"].data_type == "s"
        assert ledger["B2"].value == 42 and type(ledger["B2"].value) is int
        assert ledger["C2"].value == datetime(2026, 1, 31)
        assert ledger["A4"].value == "TOTAL" and ledger["B4"].value == "=SUM(B2:B3)"
    finally:
        book.close()

    cached = load_workbook(io.BytesIO(doc.data), data_only=True)
    try:
        assert cached["Ledger"]["B4"].value == 44.5 and cached["Ledger"]["C4"].value == 2
        ranges = [cached["Ranges"].cell(row=2, column=col).value for col in range(1, 6)]
        assert ranges == [1, 5, 2.8, 14, 5], "non-Excel readers see real numbers, not 0"
    finally:
        cached.close()

    with zipfile.ZipFile(io.BytesIO(doc.data)) as archive:
        assert b'fullCalcOnLoad="1"' in archive.read("xl/workbook.xml")


def test_formula_cached_values_match_recompute():
    doc = _gen({"sheets": [{"name": "A", "rows": [
        [1], [2], [3], [4.5],
        [{"formula": "=SUM(A1:A4)", "value": 10.5}],
        [{"formula": "=AVERAGE(A1:A4)", "value": 2.625}],
        [{"formula": "=COUNT(A1:A4)", "value": 4}],
        [{"formula": "=MIN(A1:A4)", "value": 1}],
        [{"formula": "=MAX(A1:A4)", "value": 4.5}],
        [{"formula": "=sum(a1:a4)", "value": 10.5}]]}]})
    assert doc.validation_state == "passed"
    assert _cached_grid(doc.data, "A")[4][0] == 10.5

    with pytest.raises(DocumentGenerationError, match="recompute"):
        _gen({"sheets": [{"name": "A", "rows": [
            [1], [2], [3], [{"formula": "=SUM(A1:A3)", "value": 999}]]}]})
    with pytest.raises(DocumentGenerationError, match="#DIV/0!"):
        _gen({"sheets": [{"name": "A", "rows": [
            ["x"], ["y"], [{"formula": "=AVERAGE(A1:A2)", "value": 1}]]}]})


def test_unsupported_formula_functions_become_warnings_with_declared_cached_values():
    doc = _gen({"sheets": [{"name": "W", "rows": [
        [7, {"formula": "=IF(A1>1, 7, 0)", "value": 7},
            {"formula": "=A1*2", "value": 14}]]}]})
    assert doc.validation_state == "passed_with_warnings"
    codes = {finding["code"] for finding in doc.findings}
    assert codes == {"formula_not_recomputed"} and len(doc.findings) == 2
    assert any("IF" in finding["detail"] for finding in doc.findings)
    grid = _cached_grid(doc.data, "W")
    assert grid[0][1] == 7 and grid[0][2] == 14, "the cached value still comes from the spec"


def test_cell_types_and_text_ids():
    doc = _gen({"sheets": [{"name": "T", "rows": [
        ["00123", 123, {"date": "2026-01-31"}]]}]})
    assert doc.validation_state == "passed"
    book = load_workbook(io.BytesIO(doc.data))
    try:
        sheet = book["T"]
        assert sheet["A1"].value == "00123" and sheet["A1"].data_type == "s"
        assert sheet["B1"].value == 123 and sheet["B1"].data_type == "n"
        assert isinstance(sheet["C1"].value, datetime)
        assert sheet["C1"].value.date() == date(2026, 1, 31)
    finally:
        book.close()


def test_sheet_names_sanitized_deduped_and_disclosed():
    doc = _gen({"sheets": [{"name": name, "rows": []} for name in (
        "Q1[2026]:final?", "r" * 40, "Same", "same", "", "x/y")]})
    expected = ["Q12026final", "r" * 31, "Same", "same_2", "Sheet5", "xy"]
    assert doc.validation_state == "passed", "a disclosed guard is not a warning state"
    book = load_workbook(io.BytesIO(doc.data), read_only=True)
    try:
        assert book.sheetnames == expected
        assert all(len(name) <= 31 for name in book.sheetnames)
    finally:
        book.close()
    sanitized = [finding for finding in doc.findings
                 if finding["code"] == "sheet_name_sanitized"]
    assert len(sanitized) == 5


def test_preview_data_shape_is_bounded_and_json_safe():
    doc = _gen({"sheets": [{"name": "P", "header": ["Name", "Note"],
                            "rows": [[7, "z" * 500, {"date": "2026-01-31"},
                                      {"formula": "=COUNT(A2:A2)", "value": 1}]]
                                     + [[5, ""]] * 11}]})
    preview = doc.preview_data
    assert preview["kind"] == "grid"
    [sheet] = preview["sheets"]
    assert sheet["name"] == "P" and sheet["rows"] == 12 and sheet["cols"] == 4
    assert len(sheet["sample"]) == 8
    assert sheet["sample"][0] == ["Name", "Note"]
    first = sheet["sample"][1]
    assert first[0] == 7 and len(first[1]) <= 121
    assert first[2] == "2026-01-31" and first[3] == 1, "preview shows cached values, JSON-safe"
    json.dumps(preview)


def test_bounds_are_rejected():
    with pytest.raises(DocumentGenerationError, match="20 sheets"):
        _gen({"sheets": [{"name": f"S{i}", "rows": []} for i in range(21)]})
    with pytest.raises(DocumentGenerationError, match="100,000 rows"):
        _gen({"sheets": [{"name": "Big", "rows": [[1]] * 100_001}]})
    with pytest.raises(DocumentGenerationError, match="256 columns"):
        _gen({"sheets": [{"name": "Wide",
                          "header": [str(i) for i in range(257)], "rows": []}]})
    with pytest.raises(DocumentGenerationError, match="256 columns"):
        _gen({"sheets": [{"name": "Wide", "rows": [[0] * 257]}]})
    with pytest.raises(DocumentGenerationError, match="col_widths"):
        _gen({"sheets": [{"name": "S", "rows": [[1]], "col_widths": [10, 20]}]})


def test_recompute_budget_exhaustion_discloses_instead_of_lying(monkeypatch):
    monkeypatch.setattr(xlsx_module, "MAX_RECOMPUTE_CELLS", 2)
    doc = _gen({"sheets": [{"name": "B", "rows": [
        [1, 2, 3],
        [{"formula": "=SUM(A1:C1)", "value": 6}],
        [{"formula": "=SUM(A1:C1)", "value": 6}]]}]})
    assert doc.validation_state == "passed_with_warnings"
    assert any("budget" in finding["detail"] for finding in doc.findings)
    assert _cached_grid(doc.data, "B")[1][0] == 6, "the cached value still comes from the spec"


def test_bad_specs_raise_instead_of_coercing():
    cases = [
        ("missing sheets", {}),
        ("empty sheets", {"sheets": []}),
        ("sheets not a list", {"sheets": "no"}),
        ("sheet not an object", {"sheets": ["x"]}),
        ("missing name", {"sheets": [{"rows": []}]}),
        ("name not a string", {"sheets": [{"name": 3, "rows": []}]}),
        ("missing rows", {"sheets": [{"name": "S"}]}),
        ("rows not a list", {"sheets": [{"name": "S", "rows": "x"}]}),
        ("row not a list", {"sheets": [{"name": "S", "rows": ["x"]}]}),
        ("unknown sheet key", {"sheets": [{"name": "S", "rows": [], "style": "x"}]}),
        ("header not a list", {"sheets": [{"name": "S", "header": "H", "rows": []}]}),
        ("header item not a string", {"sheets": [{"name": "S", "header": [1], "rows": []}]}),
        ("freeze without header", {"sheets": [{"name": "S", "rows": [], "freeze_header": True}]}),
        ("freeze not a bool", {"sheets": [{"name": "S", "header": ["H"], "rows": [],
                                          "freeze_header": "yes"}]}),
        ("col_widths not a list", {"sheets": [{"name": "S", "rows": [], "col_widths": "w"}]}),
        ("col_widths bool item", {"sheets": [{"name": "S", "rows": [], "col_widths": [True]}]}),
        ("negative width", {"sheets": [{"name": "S", "rows": [], "col_widths": [-1]}]}),
        ("boolean cell", {"sheets": [{"name": "S", "rows": [[True]]}]}),
        ("None cell", {"sheets": [{"name": "S", "rows": [[None]]}]}),
        ("nested list cell", {"sheets": [{"name": "S", "rows": [[["x"]]]}]}),
        ("formula without value", {"sheets": [{"name": "S",
                                               "rows": [[{"formula": "=SUM(A1:A2)"}]]}]}),
        ("formula value not a number", {"sheets": [{"name": "S",
                                                    "rows": [[{"formula": "=SUM(A1:A2)",
                                                               "value": "6"}]]}]}),
        ("formula not a string", {"sheets": [{"name": "S",
                                              "rows": [[{"formula": 5, "value": 5}]]}]}),
        ("date not ISO", {"sheets": [{"name": "S", "rows": [[{"date": "31/01/2026"}]]}]}),
        ("date not real", {"sheets": [{"name": "S", "rows": [[{"date": "2026-02-30"}]]}]}),
        ("date not a string", {"sheets": [{"name": "S", "rows": [[{"date": 20260131}]]}]}),
        ("cell object with extra keys", {"sheets": [{"name": "S",
                                                     "rows": [[{"date": "2026-01-31",
                                                                "format": "bold"}]]}]}),
    ]
    for label, spec in cases:
        with pytest.raises(DocumentGenerationError, match="bad xlsx specification"):
            _gen(spec)
    with pytest.raises(DocumentGenerationError, match="must be an object"):
        generate("xlsx", ["not", "a", "dict"])
